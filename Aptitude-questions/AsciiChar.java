public class AsciiChar {
    public static void main(String[] args) {
        
        char a = 'a'; // ASCII value is 97
        int asciiOfC = 'c'; // ASCII value is 99

        int asciiNumber = (int) a; // cast char 'a' to int

        System.out.println("ASCII value of 'c' is: " + asciiOfC);
        System.out.println("ASCII value of 'a' is: " + asciiNumber);
    }
}
