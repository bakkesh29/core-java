        int dividend = 30;
        int divisor = 6;

        // Performs integer division: 30 / 6 = 5
        // Stores the result in quotient
        int quotient = dividend/divisor;

        // Performs the modulus operation: 30 % 6 = 0
        // Stores the remainder in reminder
