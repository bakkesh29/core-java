class Mic {
    void on() {
        System.out.println("Mic ON");
    }

    void off() {
        System.out.println("Mic OFF");
    }

    void increaseVolume() {
        System.out.println("Volume up");
    }

    void decreaseVolume() {
        System.out.println("Volume down");
    }

    void mute() {
        System.out.println("Mic muted");
    }
}